<#
.SYNOPSIS
    Batch-exports BarTender .btw label formats to raw Argox PPLB .prn files.

.DESCRIPTION
    .btw is a proprietary BarTender binary format that cannot be parsed outside
    BarTender. This script drives BarTender itself from the command line and
    "prints" every .btw to a file instead of a physical printer. The resulting
    .prn files contain the exact printer commands generated by the Argox driver:
    label width (q), length and gap (Q), darkness (D), speed (S), reference
    offsets (R), print direction (Z) and every field at its exact dot position.
    These .prn files are what the Orange Pi orchestrator imports as templates.

    How it works:
      1. A local printer port is created that writes to a file on disk.
      2. Either an existing Argox printer is temporarily pointed at that port
         (-PrinterName, preserves all driver settings; original port restored
         afterwards), or a dedicated export printer is created with the
         installed Argox driver.
      3. For every .btw: bartend.exe /F=<file> /PRN=<printer> /P /X is run,
         the spooled output is captured and moved to OutputDir, keeping the
         original folder structure.
      4. Already-exported files are skipped, so the script can be re-run to
         resume after an interruption.

    Requirements:
      - Run from an Administrator PowerShell (needed to manage printers/ports).
      - BarTender installed with command-line printing available.
      - An Argox OS-214 driver installed (Seagull driver is fine).
      - Close BarTender before running (the /X flag closes the instance).

.EXAMPLE
    .\convert_btw_batch.ps1 -SourceDir "D:\Labels"

.EXAMPLE
    .\convert_btw_batch.ps1 -SourceDir "D:\Labels" -PrinterName "Argox OS-214 plus PPLB"
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$SourceDir,

    [string]$OutputDir,

    # Existing Windows printer to reuse (port is swapped temporarily, then restored).
    [string]$PrinterName,

    # Driver name filter used when creating a dedicated export printer.
    [string]$DriverFilter = "*OS-214*",

    [string]$BartendPath,

    [int]$TimeoutSec = 90,

    # Remove the dedicated export printer and port when finished.
    [switch]$Cleanup
)

$ErrorActionPreference = "Stop"

function Write-Info($msg) { Write-Host "[INFO] $msg" }
function Write-Warn($msg) { Write-Host "[WARN] $msg" -ForegroundColor Yellow }
function Write-Fail($msg) { Write-Host "[FAIL] $msg" -ForegroundColor Red }

# --- 1. Preconditions --------------------------------------------------------
$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    Write-Fail "Run this script from an Administrator PowerShell window."
    exit 1
}

$SourceDir = (Resolve-Path $SourceDir).Path.TrimEnd('\')
if (-not $OutputDir) { $OutputDir = Join-Path $SourceDir "prn_export" }
New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null
$OutputDir = (Resolve-Path $OutputDir).Path.TrimEnd('\')

if (-not $BartendPath) {
    $roots = @("$env:ProgramFiles\Seagull", "${env:ProgramFiles(x86)}\Seagull") | Where-Object { $_ -and (Test-Path $_) }
    $found = $roots | ForEach-Object { Get-ChildItem -Path $_ -Recurse -Filter "bartend.exe" -ErrorAction SilentlyContinue } |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1
    if (-not $found) {
        Write-Fail "bartend.exe not found under Program Files\Seagull. Pass -BartendPath explicitly."
        exit 1
    }
    $BartendPath = $found.FullName
}
Write-Info "BarTender: $BartendPath"

if (Get-Process -Name "bartend" -ErrorAction SilentlyContinue) {
    Write-Fail "BarTender is currently open. Save your work, close it, and re-run."
    exit 1
}

# --- 2. File port + printer --------------------------------------------------
$stageDir = Join-Path $env:SystemDrive "btw_export_stage"
New-Item -ItemType Directory -Force -Path $stageDir | Out-Null
$stageFile = Join-Path $stageDir "current.prn"

if (-not (Get-PrinterPort -Name $stageFile -ErrorAction SilentlyContinue)) {
    Add-PrinterPort -Name $stageFile
    Write-Info "Created file port: $stageFile"
}

$exportPrinter = $null
$originalPort = $null
$createdPrinter = $false

if ($PrinterName) {
    $p = Get-Printer -Name $PrinterName -ErrorAction SilentlyContinue
    if (-not $p) {
        Write-Fail "Printer '$PrinterName' not found. Installed printers:"
        Get-Printer | ForEach-Object { Write-Host "    $($_.Name)" }
        exit 1
    }
    $exportPrinter = $p.Name
    $originalPort = $p.PortName
    Write-Info "Reusing printer '$exportPrinter' (original port '$originalPort' will be restored)."
} else {
    $driver = Get-PrinterDriver | Where-Object { $_.Name -like $DriverFilter } | Select-Object -First 1
    if (-not $driver) {
        Write-Fail "No printer driver matching '$DriverFilter'. Installed drivers:"
        Get-PrinterDriver | ForEach-Object { Write-Host "    $($_.Name)" }
        Write-Host "Re-run with -DriverFilter '<name>' or -PrinterName '<existing printer>'."
        exit 1
    }
    $exportPrinter = "Argox OS-214 (PRN Export)"
    if (-not (Get-Printer -Name $exportPrinter -ErrorAction SilentlyContinue)) {
        Add-Printer -Name $exportPrinter -DriverName $driver.Name -PortName $stageFile
        $createdPrinter = $true
        Write-Info "Created export printer '$exportPrinter' using driver '$($driver.Name)'."
    } else {
        Write-Info "Using existing export printer '$exportPrinter'."
    }
    Write-Warn "A new printer uses default driver settings. If output offsets look wrong, re-run with -PrinterName set to the Argox printer the labels were designed on."
}

# --- 3. Export loop ----------------------------------------------------------
$files = Get-ChildItem -Path $SourceDir -Recurse -Filter "*.btw" -File |
    Where-Object { $_.FullName -notlike "$OutputDir*" }
$total = $files.Count
Write-Info "Found $total .btw files in $SourceDir"

$logPath = Join-Path $OutputDir "export_log.csv"
$results = New-Object System.Collections.Generic.List[object]
$ok = 0; $skipped = 0; $failed = 0; $i = 0

try {
    if ($originalPort) { Set-Printer -Name $exportPrinter -PortName $stageFile }

    foreach ($f in $files) {
        $i++
        $rel = $f.FullName.Substring($SourceDir.Length).TrimStart('\')
        $outPath = Join-Path $OutputDir ([IO.Path]::ChangeExtension($rel, ".prn"))
        $label = "[$i/$total] $rel"

        if ((Test-Path $outPath) -and ((Get-Item $outPath).Length -gt 0)) {
            $skipped++
            $results.Add([pscustomobject]@{ File = $rel; Status = "skipped"; Bytes = (Get-Item $outPath).Length; Note = "already exported" })
            continue
        }

        Remove-Item $stageFile -Force -ErrorAction SilentlyContinue

        $btArgs = @("/F=`"$($f.FullName)`"", "/PRN=`"$exportPrinter`"", "/P", "/X", "/NOSPLASH", "/MIN=TaskBar")
        $proc = Start-Process -FilePath $BartendPath -ArgumentList $btArgs -PassThru
        if (-not $proc.WaitForExit($TimeoutSec * 1000)) {
            try { $proc.Kill() } catch {}
            $failed++
            Write-Fail "$label - BarTender did not finish in $TimeoutSec s (probably a data-entry prompt or dialog)."
            $results.Add([pscustomobject]@{ File = $rel; Status = "failed"; Bytes = 0; Note = "timeout / dialog" })
            continue
        }

        # Wait for the spooler to finish writing the file (size stable for 1.5 s).
        $deadline = (Get-Date).AddSeconds($TimeoutSec)
        $lastSize = -1; $stableTicks = 0
        while ((Get-Date) -lt $deadline) {
            if (Test-Path $stageFile) {
                $size = (Get-Item $stageFile).Length
                if ($size -gt 0 -and $size -eq $lastSize) { $stableTicks++ } else { $stableTicks = 0 }
                $lastSize = $size
                if ($stableTicks -ge 3) { break }
            }
            Start-Sleep -Milliseconds 500
        }

        if ((Test-Path $stageFile) -and ((Get-Item $stageFile).Length -gt 0)) {
            New-Item -ItemType Directory -Force -Path (Split-Path $outPath) | Out-Null
            Move-Item -Path $stageFile -Destination $outPath -Force
            $bytes = (Get-Item $outPath).Length
            $ok++
            Write-Info "$label -> $bytes bytes"
            $results.Add([pscustomobject]@{ File = $rel; Status = "ok"; Bytes = $bytes; Note = "" })
        } else {
            $failed++
            Write-Fail "$label - no print output captured."
            $results.Add([pscustomobject]@{ File = $rel; Status = "failed"; Bytes = 0; Note = "no spool output" })
        }
    }
}
finally {
    if ($originalPort) {
        Set-Printer -Name $exportPrinter -PortName $originalPort
        Write-Info "Restored '$exportPrinter' to port '$originalPort'."
    }
    if ($Cleanup -and $createdPrinter) {
        Remove-Printer -Name $exportPrinter -ErrorAction SilentlyContinue
        Write-Info "Removed export printer '$exportPrinter'."
    }
    if ($Cleanup) {
        Remove-PrinterPort -Name $stageFile -ErrorAction SilentlyContinue
    }
    $results | Export-Csv -Path $logPath -NoTypeInformation -Encoding UTF8
}

Write-Host ""
Write-Info "Done. Exported: $ok  Skipped: $skipped  Failed: $failed  (of $total)"
Write-Info "Output folder: $OutputDir"
Write-Info "Log: $logPath"
if ($failed -gt 0) {
    Write-Warn "Failed files usually have a data-entry form or prompt. Open those in BarTender and use File > Print > Print to File manually, or re-run the script to retry."
}
